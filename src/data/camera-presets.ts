function buildPreset(row: (typeof ROWS)[number]): CameraPreset {
  const [
    id,
    brand,
    model,
    category,
    make,
    lensModel,
    software,
    iso,
    fNumber,
    focalLength,
    focal35,
    exposureTime,
  ] = row;
  return {
    id,
    brand,
    model,
    category,
    tags: {
      "EXIF:Make": make,
      "EXIF:Model": model,
      "EXIF:LensModel": lensModel,
      "EXIF:Software": software,
      "EXIF:ISO": iso,
      "EXIF:FNumber": fNumber,
      "EXIF:FocalLength": focalLength,
      "EXIF:FocalLengthIn35mmFormat": focal35,
      "EXIF:ExposureTime": exposureTime,
    },
  };
}

export const CAMERA_PRESETS: CameraPreset[] = ROWS.map(buildPreset);

export const PRESET_CATEGORIES: {
  id: PresetCategory | "all";
  labelKey: string;
}[] = [
  { id: "all", labelKey: "swap.category.all" },
  { id: "phone", labelKey: "swap.category.phone" },
  { id: "camera", labelKey: "swap.category.camera" },
  { id: "drone", labelKey: "swap.category.drone" },
  { id: "action", labelKey: "swap.category.action" },
];

/** Brands in first-seen order, for the picker UI. */
export const PRESET_BRANDS: string[] = Array.from(
  new Set(CAMERA_PRESETS.map((p) => p.brand)),
);

export function findPreset(id: string): CameraPreset | undefined {
  return CAMERA_PRESETS.find((p) => p.id === id);
}
